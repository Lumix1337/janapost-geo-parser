fun stringsFor(lang: AppLang): Strings = if (lang.resolved() == AppLang.EN) En else Ru

fun Strings.countryName(id: String): String = when (id) {
    "kz" -> kazakhstan
    "ru" -> russia
    "kg" -> kyrgyzstan
    "uz" -> uzbekistan
    "cn" -> china
    else -> id
}

fun Strings.statusName(id: String): String = when (id) {
    "pending" -> pending
    "in_stock" -> inStock
    "on_road" -> onRoad
    "sorting" -> sorting
    "send_branch" -> sendBranch
    "branch" -> atBranch
    "at_courier" -> atCourier
    "received" -> received
    "accepted" -> accepted
    "lost" -> findLost
    else -> id
}

